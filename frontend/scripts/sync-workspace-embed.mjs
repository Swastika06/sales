// Bundle the existing local login and workspace into the self-contained ezextend file.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { parse } from "@babel/parser";
import postcss from "postcss";

const root = fileURLToPath(new URL("..", import.meta.url));
const destination = path.join(root, "ezextend/react-design.jsx");
const configPath = path.join(root, "src/api/config.ts");
const bundle = await build({
  absWorkingDir: root,
  entryPoints: ["src/embedded/Workspace.tsx"],
  bundle: true, write: false, format: "iife", globalName: "TcgEmbeddedWorkspace",
  platform: "browser", target: "es2022", jsx: "automatic",
  minify: true, legalComments: "inline",
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [{
    name: "host-react-and-widget-config",
    setup(builder) {
      builder.onResolve({ filter: /^react(?:\/jsx-runtime)?$/ }, args => ({ path: args.path, namespace: "host-react" }));
      builder.onLoad({ filter: /.*/, namespace: "host-react" }, args => ({
        contents: args.path === "react"
          ? "module.exports = hostReact;"
          : "export const Fragment = hostReact.Fragment; export function jsx(type, props, key) { return hostReact.createElement(type, key === undefined ? props : { ...props, key }); } export const jsxs = jsx;",
        loader: "js",
      }));
      builder.onLoad({ filter: /[\\/]api[\\/]config\.ts$/ }, args => {
        if (path.resolve(args.path) !== configPath) return;
        return {
          contents: `export const apiConfig = {
            apiBaseUrl: settings.apiBaseUrl.replace(/\\/+$/, ""),
            tokenStorageKey: settings.tokenStorageKey || "tcg_partner_widget_token:" + new URL(settings.apiBaseUrl, window.location.href).href.replace(/\\/+$/, ""),
            requestTimeoutMs: settings.requestTimeoutMs,
          };`,
          loader: "ts",
        };
      });
    },
  }],
});

const scope = "[data-tcg-workspace]";
const css = postcss.parse(
  fs.readFileSync(path.join(root, "src/styles.css"), "utf8") + "\n" +
  fs.readFileSync(path.join(root, "src/features/onboarding/onboarding.css"), "utf8")
);
css.walkAtRules("import", rule => rule.remove());
css.walkRules(rule => {
  if (rule.parent.type === "atrule" && rule.parent.name.endsWith("keyframes")) return;
  rule.selectors = rule.selectors.map(selector => {
    const value = selector.trim();
    if (/^(:root|html|body)$/.test(value)) return scope;
    return scope + " " + value;
  });
});
css.append(`
${scope} { display:block; min-width:0; width:100%; }
${scope} .embedded-workspace-toolbar { display:flex; align-items:center; padding:14px 24px; border-bottom:1px solid var(--line); background:var(--paper); }
${scope} .embedded-workspace-toolbar a { color:var(--green); font-size:13px; font-weight:700; text-decoration:none; }
`);

const begin = "// BEGIN GENERATED WORKSPACE";
const end = "// END GENERATED WORKSPACE";
const generated = begin + "\n" +
  "// Generated by npm run sync:widget. Edit the shared src files, then regenerate.\n" +
  "const EMBEDDED_WORKSPACE_STYLES = " + JSON.stringify(css.toString()) + ";\n" +
  "function createEmbeddedWorkspace(settings, hostReact) {\n" +
  bundle.outputFiles[0].text + "\nreturn TcgEmbeddedWorkspace.EmbeddedWorkspace;\n}\n" + end;
let widget = fs.readFileSync(destination, "utf8");
if (widget.includes(begin)) {
  widget = widget.slice(0, widget.indexOf(begin)) + generated + widget.slice(widget.indexOf(end) + end.length);
} else {
  const start = widget.indexOf("function EzComponent(");
  if (start < 0) throw new Error("Cannot find EzComponent");
  widget = widget.slice(0, start) + generated + "\n\n" + widget.slice(start);
}
parse(widget, { sourceType: "script", plugins: ["jsx"] });
fs.writeFileSync(destination, widget);
console.log("Shared login, authenticated workspace, dependencies, and scoped styles embedded.");
